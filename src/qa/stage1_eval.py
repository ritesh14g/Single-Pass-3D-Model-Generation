"""Stage 1 (Ingest, spec §4) evaluation — the scorecard behind the Stage Lab panel.

Everything here is a pure function of the ingest stage's on-disk outputs (plus
ground truth when the input was generated by ``src.qa.synthetic``), so the same
numbers are available to the UI, to tests, and later to the QA report.

KPI groups and the measuring technique behind each:

  * **Frame selection (§4.3 acceptance test)** — overlap distribution of the
    kept pairs against the [0.70, 0.80] band; pairs below 50% overlap (a broken
    match graph); extrapolated time to select a 10-minute 4K clip against the
    60 s acceptance budget; decode efficiency.
  * **Blur gate (§5.2, used by §4.3)** — reject fraction against the coverage
    cap, coverage warnings. With ground truth: recall on truly blurred frames,
    false-reject rate on sharp frames, blurred frames that leaked into the set.
  * **Telemetry (§4.2)** — which sensors were found, fraction of selected frames
    with a GPS fix, telemetry/video duration agreement. With ground truth: the
    horizontal error of the parsed track against what was written.
  * **Measured accuracy of the overlap estimator** (ground truth only) — mean
    absolute error of measured overlap against the true geometric overlap.

Status per KPI: ``pass`` / ``warn`` / ``fail`` against the stated target, or
``info`` where the spec sets no target. The stage score is the share of scored
KPIs passed, with a warn counting half.
"""

from __future__ import annotations

import json
import math
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from src.qa.synthetic import METRES_PER_DEGREE_LAT, true_lonlat, true_pair_overlap

PASS, WARN, FAIL, INFO = "pass", "warn", "fail", "info"

# Reference clip for the §4.3 acceptance test: 10 minutes of 3840x2160.
REFERENCE_DURATION_S = 600.0
REFERENCE_PIXELS = 3840 * 2160
SELECTION_BUDGET_S = 60.0
OVERLAP_BAND = (0.70, 0.80)


@dataclass
class Kpi:
    key: str
    group: str
    label: str
    value: Any
    target: str
    status: str
    detail: str = ""
    unit: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class StageEvaluation:
    stage: str
    kpis: list[Kpi] = field(default_factory=list)
    has_ground_truth: bool = False

    @property
    def score(self) -> float | None:
        scored = [k for k in self.kpis if k.status in (PASS, WARN, FAIL)]
        if not scored:
            return None
        points = sum(1.0 if k.status == PASS else 0.5 if k.status == WARN else 0.0 for k in scored)
        return round(100.0 * points / len(scored), 1)

    def counts(self) -> dict[str, int]:
        return {s: sum(1 for k in self.kpis if k.status == s) for s in (PASS, WARN, FAIL, INFO)}

    def table(self) -> pd.DataFrame:
        return pd.DataFrame([k.to_dict() for k in self.kpis])

    def to_dict(self) -> dict[str, Any]:
        return {
            "stage": self.stage,
            "score": self.score,
            "counts": self.counts(),
            "has_ground_truth": self.has_ground_truth,
            "kpis": [k.to_dict() for k in self.kpis],
        }


@dataclass
class IngestOutputs:
    """The ingest stage's artifacts, loaded."""

    selection: pd.DataFrame
    evaluations: pd.DataFrame
    telemetry: pd.DataFrame
    frame_telemetry: pd.DataFrame
    metrics: dict[str, Any]

    @classmethod
    def load(cls, stage_dir: Path | str, metrics: dict[str, Any]) -> "IngestOutputs":
        stage_dir = Path(stage_dir)

        def read(name: str) -> pd.DataFrame:
            path = stage_dir / name
            return pd.read_parquet(path) if path.is_file() else pd.DataFrame()

        return cls(
            selection=read("frames.parquet"),
            evaluations=read("blur_evaluations.parquet"),
            telemetry=read("telemetry.parquet"),
            frame_telemetry=read("frame_telemetry.parquet"),
            metrics=metrics,
        )


# --------------------------------------------------------------------------
# Scoring
# --------------------------------------------------------------------------
def _band_status(value: float, lo: float, hi: float, slack: float) -> str:
    if lo <= value <= hi:
        return PASS
    if lo - slack <= value <= hi + slack:
        return WARN
    return FAIL


def evaluate_ingest(outputs: IngestOutputs, cfg: Any, truth: dict | None = None) -> StageEvaluation:
    ev = StageEvaluation(stage="ingest", has_ground_truth=truth is not None)
    metrics = outputs.metrics
    video = metrics.get("video", {})
    selection_metrics = metrics.get("selection", {})
    sel = outputs.selection

    # -- Frame selection ----------------------------------------------------
    overlaps = sel["overlap_prev"].to_numpy(dtype=float)[1:] if len(sel) > 1 else np.array([])
    if overlaps.size:
        median = float(np.median(overlaps))
        ev.kpis.append(Kpi(
            "overlap_median", "Frame selection", "Median consecutive overlap", round(median, 3),
            f"{OVERLAP_BAND[0]:.2f}–{OVERLAP_BAND[1]:.2f} (§4.3)",
            _band_status(median, *OVERLAP_BAND, slack=0.05),
            "Overlap between each kept frame and the previous one, measured by verified optical flow.",
        ))
        low = int((overlaps < 0.5).sum())
        ev.kpis.append(Kpi(
            "overlap_low_pairs", "Frame selection", "Pairs below 50% overlap", low, "0",
            PASS if low == 0 else WARN if low <= 2 else FAIL,
            "Each such pair is a likely break in the SfM match graph.",
        ))
    else:
        ev.kpis.append(Kpi("overlap_median", "Frame selection", "Median consecutive overlap", None,
                           "needs ≥2 frames", FAIL, "Fewer than two frames were selected."))

    min_frames = int(cfg.get_path("ingest.frame_selection.min_frames"))
    n_selected = len(sel)
    ev.kpis.append(Kpi(
        "frames_selected", "Frame selection", "Frames selected", n_selected, f"≥ {min_frames}",
        PASS if n_selected >= min_frames else WARN if n_selected >= max(min_frames // 2, 2) else FAIL,
        f"from {video.get('frame_count', '?')} video frames",
    ))

    timing = metrics.get("timing", {})
    select_s = float(timing.get("profile_s", 0.0)) + float(timing.get("select_s", 0.0))
    decode_s = min(float(timing.get("decode_s", 0.0)), select_s)
    duration = float(video.get("duration_s") or 0.0)
    pixels = float(video.get("width", 0) or 0) * float(video.get("height", 0) or 0)
    if select_s > 0 and duration > 0 and pixels > 0 and n_selected > 0:
        # Two costs that scale differently, so they are projected separately:
        #  * analysis (flow, verification, blur metrics) runs at a fixed working
        #    width, so it scales with the number of frames KEPT — this clip's
        #    keep rate over 10 minutes, capped by max_frames;
        #  * decode traverses the whole clip, so it scales with duration and
        #    with pixel count (4K vs this input).
        max_frames = int(cfg.get_path("ingest.frame_selection.max_frames"))
        analysis_s = max(select_s - decode_s, 0.0)
        per_frame_s = analysis_s / n_selected
        expected_frames = min(max_frames, n_selected / duration * REFERENCE_DURATION_S)
        analysis_proj = per_frame_s * expected_frames
        decode_proj = decode_s * (REFERENCE_DURATION_S / duration) * (REFERENCE_PIXELS / pixels)
        projected = analysis_proj + decode_proj
        ev.kpis.append(Kpi(
            "projected_4k_10min_s", "Frame selection", "Projected selection time, 10-min 4K clip",
            round(projected, 1), f"< {SELECTION_BUDGET_S:.0f} s (§4.3)",
            PASS if projected < SELECTION_BUDGET_S else WARN if projected < 2 * SELECTION_BUDGET_S else FAIL,
            f"analysis {analysis_proj:.0f} s ({per_frame_s * 1000:.0f} ms per kept frame x {expected_frames:.0f} frames) "
            f"+ decode {decode_proj:.0f} s ({decode_s:.2f} s here, scaled to 10 min of 4K; software decode — "
            "hardware decode or keyframe seeking changes this). Estimate: verify on real 4K footage.",
            unit="s",
        ))
        ev.kpis.append(Kpi(
            "analysis_ms_per_kept_frame", "Frame selection", "Analysis cost per kept frame",
            round(per_frame_s * 1000, 1), "info", INFO,
            "Flow + photometric verification + blur metrics, excluding decode.", unit="ms",
        ))

    decoded = int(selection_metrics.get("decoded_frames", 0))
    total = int(video.get("frame_count") or 0)
    if total:
        fraction = decoded / total
        ev.kpis.append(Kpi(
            "decode_fraction", "Frame selection", "Frames decoded / frames in video", round(fraction, 3),
            "< 0.60", PASS if fraction < 0.6 else WARN if fraction < 1.0 else FAIL,
            "The predictive stride should decode a small fraction of the video.",
        ))

    # -- Blur gate ----------------------------------------------------------
    evals = outputs.evaluations
    blur = selection_metrics.get("blur", {})
    evaluated = int(blur.get("frames", 0))
    rejected = int(blur.get("rejected", 0))
    cap = float(cfg.get_path("condition.blur.max_reject_fraction"))
    if evaluated:
        fraction = rejected / evaluated
        ev.kpis.append(Kpi(
            "blur_reject_fraction", "Blur gate", "Rejected / evaluated", round(fraction, 3),
            f"≤ {cap:.2f} (coverage cap)", PASS if fraction <= cap else WARN,
            f"{rejected} of {evaluated} evaluated frames rejected "
            f"({blur.get('directional_rejects', 0)} for directional blur).",
        ))
    warnings = len(selection_metrics.get("coverage_warnings", []))
    ev.kpis.append(Kpi(
        "coverage_warnings", "Blur gate", "Coverage warnings (reject runs)", warnings, "0",
        PASS if warnings == 0 else WARN,
        "Runs of consecutive rejected frames — flight segments with reduced coverage.",
    ))

    # -- Telemetry ----------------------------------------------------------
    tel = metrics.get("telemetry", {})
    sensors = [name for name, key in (("GPS", "has_gps"), ("baro", "has_baro"), ("attitude", "has_attitude"),
                                      ("focal", "has_focal"), ("RTK", "has_rtk")) if tel.get(key)]
    ev.kpis.append(Kpi(
        "telemetry_source", "Telemetry", "Source and sensors found",
        f"{tel.get('source', 'none')}: {', '.join(sensors) or 'none'}", "GPS required for metric scale",
        INFO, "; ".join(tel.get("notes", [])[:3]),
    ))
    ft = outputs.frame_telemetry
    if len(ft):
        coverage = float((ft["lat"].notna() & ft["lon"].notna()).mean())
        ev.kpis.append(Kpi(
            "gps_frame_coverage", "Telemetry", "Selected frames with a GPS fix", round(coverage, 3), "≥ 0.95",
            PASS if coverage >= 0.95 else WARN if coverage >= 0.5 else FAIL,
            "Zero means a scale-free, non-georeferenced model (§4.2 path 4).",
        ))
    tel_duration = float(tel.get("duration_s") or 0.0)
    if duration > 0 and tel_duration > 0:
        ratio = tel_duration / duration
        ev.kpis.append(Kpi(
            "telemetry_duration_ratio", "Telemetry", "Telemetry span / video duration", round(ratio, 3),
            "0.95–1.05", _band_status(ratio, 0.95, 1.05, slack=0.10),
            "A mismatch suggests the sidecar belongs to a different clip or is time-offset.",
        ))

    if truth is not None:
        _ground_truth_kpis(ev, outputs, truth)
    return ev


def _ground_truth_kpis(ev: StageEvaluation, outputs: IngestOutputs, truth: dict) -> None:
    sel = outputs.selection
    if len(sel) > 1:
        idx = sel["index"].to_numpy(dtype=int)
        measured = sel["overlap_prev"].to_numpy(dtype=float)[1:]
        true = np.array([true_pair_overlap(truth, a, b) for a, b in zip(idx[:-1], idx[1:])])
        mae = float(np.mean(np.abs(measured - true)))
        ev.kpis.append(Kpi(
            "overlap_mae_vs_truth", "Ground truth", "Overlap estimator error (MAE)", round(mae, 4), "< 0.05",
            PASS if mae < 0.05 else WARN if mae < 0.10 else FAIL,
            "Measured overlap against the exact geometric overlap of the synthetic pan.",
        ))

    blurred = set(int(i) for i in truth.get("blurred_indices", []))
    evals = outputs.evaluations
    if len(evals) and blurred:
        is_blurred = evals["index"].isin(blurred)
        is_rejected = evals["verdict"] == "reject"
        if is_blurred.any():
            recall = float((is_blurred & is_rejected).sum() / is_blurred.sum())
            ev.kpis.append(Kpi(
                "blur_recall", "Ground truth", "Blurred frames rejected (recall)", round(recall, 3), "≥ 0.90",
                PASS if recall >= 0.9 else WARN if recall >= 0.7 else FAIL,
                f"{int(is_blurred.sum())} truly blurred frames were evaluated by the gate.",
            ))
        if (~is_blurred).any():
            false_reject = float((~is_blurred & is_rejected).sum() / (~is_blurred).sum())
            ev.kpis.append(Kpi(
                "blur_false_reject", "Ground truth", "Sharp frames wrongly rejected", round(false_reject, 3),
                "≤ 0.05", PASS if false_reject <= 0.05 else WARN if false_reject <= 0.15 else FAIL,
                "Coverage spent on frames that were never damaged.",
            ))
    if len(sel) and blurred:
        leaked = int(sel["index"].isin(blurred).sum())
        ev.kpis.append(Kpi(
            "blurred_frames_kept", "Ground truth", "Blurred frames in the selected set", leaked, "0",
            PASS if leaked == 0 else FAIL, "",
        ))

    ft = outputs.frame_telemetry
    if len(ft) and truth.get("speed_mps") and ft["lat"].notna().any():
        errors = []
        for row in ft.itertuples():
            if not (np.isfinite(row.lat) and np.isfinite(row.lon)):
                continue
            lon_true, lat_true = true_lonlat(truth, float(row.t))
            dx = (row.lon - lon_true) * METRES_PER_DEGREE_LAT * math.cos(math.radians(lat_true))
            dy = (row.lat - lat_true) * METRES_PER_DEGREE_LAT
            errors.append(math.hypot(dx, dy))
        if errors:
            worst = float(np.max(errors))
            ev.kpis.append(Kpi(
                "gps_parse_error_m", "Ground truth", "Parsed GPS vs written track (max)", round(worst, 3),
                "< 0.5 m", PASS if worst < 0.5 else WARN if worst < 2.0 else FAIL,
                "Parser + interpolation error only; no GPS noise was injected.", unit="m",
            ))


