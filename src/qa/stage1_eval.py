def overlap_series(outputs: IngestOutputs, truth: dict | None = None) -> pd.DataFrame:
    sel = outputs.selection
    if len(sel) < 2:
        return pd.DataFrame(columns=["pair", "frame_index", "measured", "true"])
    idx = sel["index"].to_numpy(dtype=int)
    frame = pd.DataFrame({
        "pair": np.arange(1, len(sel)),
        "frame_index": idx[1:],
        "stride": np.diff(idx),
        "measured": sel["overlap_prev"].to_numpy(dtype=float)[1:],
    })
    if truth is not None:
        frame["true"] = [true_pair_overlap(truth, a, b) for a, b in zip(idx[:-1], idx[1:])]
    return frame


def blur_timeline(outputs: IngestOutputs) -> pd.DataFrame:
    evals = outputs.evaluations.copy()
    if evals.empty:
        return evals
    evals["selected"] = evals["index"].isin(outputs.selection["index"]) if len(outputs.selection) else False
    return evals


def track_metres(frame: pd.DataFrame) -> pd.DataFrame:
    """Telemetry as local east/north metres from the first fix, for plotting."""
    if frame.empty or not frame["lat"].notna().any():
        return pd.DataFrame(columns=["t", "east_m", "north_m"])
    valid = frame[frame["lat"].notna() & frame["lon"].notna()]
    lat0, lon0 = float(valid["lat"].iloc[0]), float(valid["lon"].iloc[0])
    out = pd.DataFrame({
        "t": valid["t"].to_numpy(dtype=float),
        "east_m": (valid["lon"] - lon0) * METRES_PER_DEGREE_LAT * math.cos(math.radians(lat0)),
        "north_m": (valid["lat"] - lat0) * METRES_PER_DEGREE_LAT,
    })
    for column in ("alt_gps", "alt_baro"):
        if column in valid:
            out[column] = valid[column].to_numpy(dtype=float)
    return out


def save_evaluation(evaluation: StageEvaluation, path: Path | str) -> Path:
    path = Path(path)
    path.write_text(json.dumps(evaluation.to_dict(), indent=2, default=str), encoding="utf-8")
    return path
